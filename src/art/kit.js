const swap = { 1: '5', 2: '6', 3: '7', 4: '8', 5: '1', 6: '2', 7: '3', 8: '4' };
const flipLegs = rows => rows.map(r => r.replace(/[1-8]/g, d => swap[d]));

export const ARTS = {};
export const GLOW = new WeakMap(); // palette -> Set of chars that glow (beyond the rig's standard ones)
export function art(d) {
  const base = grid(d.base, 0, 0, d.id, 'base'), w = base[0].length, h = base.length, body = d.body || 'std', T = LEGS[body];
  if (w !== T.w) throw new Error(`art ${d.id}: ${w} wide, but body '${body}' is ${T.w}`);
  const pal = {}; for (const k in d.pal) { pal[k] = hex(d.pal[k]); pal[FAR(k)] = dimC(pal[k], .74); }
  const used = new Set(); const chk = (rows, what) => rows.forEach(r => { for (const ch of r) if (ch !== '.' && !(ch in pal)) throw new Error(`art ${d.id}.${what}: char '${ch}' is not in the palette`); else used.add(ch); });
  chk(base, 'base');
  const sig = d.sig ? grid(d.sig, w, 0, d.id, 'sig') : null; if (sig) chk(sig, 'sig'); if (sig && sig.length < d.rig.leg) throw new Error(`art ${d.id}.sig: ${sig.length} rows, needs at least ${d.rig.leg}`);
  const back = !d.back ? null : typeof d.back === 'string' ? grid(d.back, w, h, d.id, 'back') : BACKS[d.back.t].map(r => r.replace(/[123]/g, c => d.back.c[c - 1])); if (back) chk(back, 'back');
  const r = d.rig, leg = r.leg; if (h - leg !== T.rows) throw new Error(`art ${d.id}: ${h - leg} leg rows, body '${body}' has ${T.rows}`);
  const lg = d.legs; for (const ch of lg) if (!(ch in pal)) throw new Error(`art ${d.id}.legs: '${ch}' is not in the palette`);
  const role = { 1: lg[0], 2: lg[1], 3: lg[2], 4: lg[3], 5: FAR(lg[0]), 6: FAR(lg[1]), 7: FAR(lg[2]), 8: FAR(lg[3]), 9: lg[4] || lg[0], 0: lg[5] || lg[1] };
  const paint = rows => rows.map(row => row.replace(/[0-9]/g, c => role[c]));
  const lead = rows => { let n = 0; while (n < rows.length && !/[^.]/.test(rows[n])) n++; return n; };
  const frames = { crouchUp: lead(T.crouch), run: [...T.run, ...T.run.map(flipLegs)].map(paint), bob: [...T.bob, ...T.bob], jump: paint(T.jump), fall: paint(T.fall), crouch: paint(T.crouch), fly: paint(T.fly) };
  const hd = r.hide;
  const anim = { leg, mid: r.mid, armC: r.arm, tipC: r.tip, aw: r.aw, al: r.al, fs: r.fs, sh: r.sh, hide: rect(hd[0], hd[1], hd[2], hd[3]), blink: r.blink, lid: r.lid, cape: '', claws: r.claws, sway: r.sway ?? 1 };
  for (const ch of (r.arm + r.tip)) if (!(ch in pal)) throw new Error(`art ${d.id}.rig: arm char '${ch}' is not in the palette`);
  GLOW.set(pal, new Set(d.glow || ''));
  return ARTS[d.id] = { id: d.id, body, w, h, pal, spr: base, sig, sigUp: sig ? sig.length - leg : 0, back, frames, anim, glow: d.glow || '' };
}

// ---- shading: what turns flat hand-drawn colour into a lit, outlined sprite. Shared by the game and the tools.
// The key light sits up and to the left in world space, so it is worked out after the sprite is flipped and posed:
// a pixel open to the top or left catches a rim light, one open to the bottom or right falls into shade, and the
// outline takes a dark tint of the colour it wraps instead of flat black.
export const lit = (c, k) => { const r = c & 255, g = (c >> 8) & 255, b = (c >> 16) & 255; return ((255 << 24) | (Math.min(255, b + (255 - b) * k) << 16) | (Math.min(255, g + (255 - g) * k) << 8) | Math.min(255, r + (255 - r) * k)) >>> 0; };
export const shade = (c, k) => ((255 << 24) | ((((c >> 16) & 255) * k | 0) << 16) | ((((c >> 8) & 255) * k | 0) << 8) | ((c & 255) * k | 0)) >>> 0;
export const inkOf = c => { const r = c & 255, g = (c >> 8) & 255, b = (c >> 16) & 255; return ((255 << 24) | ((b * .22 + 10 | 0) << 16) | ((g * .2 + 7 | 0) << 8) | (r * .22 + 8 | 0)) >>> 0; };
