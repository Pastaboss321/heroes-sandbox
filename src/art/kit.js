// Hero art kit. Every hero's look is one art({...}) call in src/art/<hero>.js: hand-drawn pixel grids plus the
// rig numbers the animation needs. Nothing here touches the DOM, so the same data draws in the game and in tools.
//
//   base   the idle frame, facing right. '.' is empty; every other char is a palette key.
//   sig    the signature pose: the upper body only (everything above the leg row). It may be taller than the base's
//          upper body; the extra rows rise above the head (a raised hammer, a lifted shield). Legs come from the stance.
//   back   an optional layer drawn behind the body that sways on its own: capes, coats, long hair. Either a grid or
//          { t:'cape'|'tatter'|'coat'|'half', c:[edge, cloth, fold] } to recolour one of the shared shapes (BACKS).
//   legs   how the shared hand-drawn leg frames (run / jump / fall / crouch / fly, in LEGS below) are coloured for
//          this hero: [thigh light, thigh dark, boot light, boot dark, hip light, hip dark].
//   rig    leg  first leg row            mid  columns left of this are the far leg
//          arm, tip  [light, mid, dark] chars for a posed arm and its fist
//          aw, al, fs  arm width, arm length, fist size        sh  front shoulder [x,y]
//          hide [x0,x1,y0,y1]  the hanging front arm, removed while the arm is posed (mirrored for the far arm)
//          blink, lid  eye char and what it turns into for a blink
const hex = h => { const v = parseInt(h.slice(1), 16); return ((255 << 24) | ((v & 255) << 16) | (((v >> 8) & 255) << 8) | ((v >> 16) & 255)) >>> 0; };
const dimC = (c, k) => ((255 << 24) | ((((c >> 16) & 255) * k | 0) << 16) | ((((c >> 8) & 255) * k | 0) << 8) | ((c & 255) * k | 0)) >>> 0;
export const FAR = ch => String.fromCharCode(ch.charCodeAt(0) + 0x2400); // the far-leg (dimmed) twin of a palette char
const grid = (s, w, h, id, what) => {
  const rows = s.replace(/^\n/, '').replace(/\n\s*$/, '').split('\n');
  if (h && rows.length !== h) throw new Error(`art ${id}.${what}: ${rows.length} rows, wanted ${h}`);
  rows.forEach((r, i) => { if (r.length !== (w || rows[0].length)) throw new Error(`art ${id}.${what}: row ${i} is ${r.length} wide ("${r}")`); });
  return rows;
};
const rect = (x0, x1, y0, y1) => { const r = []; for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) r.push([x, y]); return r; };

